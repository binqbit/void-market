import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import Mock, patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts/localnet"))

import compose
from cleanup import reset_localnet


class ComposeCleanupTests(unittest.TestCase):
    def create_state(self, parent):
        state = parent / "localnet"
        state.mkdir()
        for name in ("chains", "media", "artifacts", "secrets", "identity-parent"):
            (state / name).mkdir()
            (state / name / "retained-data").write_text("keep until reset")

        values = {
            "COMPOSE_PROJECT_NAME": "cleanup-test",
            "LOCAL_UID": str(os.getuid()),
            "LOCAL_GID": str(os.getgid()),
            "LOCALNET_STATE_DIR": str(state / "chains"),
            "DEV_MEDIA_ROOT": str(state / "media"),
            "ARBITER_ARTIFACT_ROOT": str(state / "artifacts"),
            "CUSTODY_MASTER_KEY_FILE": str(state / "secrets" / "custody.key"),
            "ARBITER_SIGNING_KEY_FILE": str(state / "secrets" / "node.key"),
            "ARBITER_SERVICE_TOKEN_FILE": str(state / "secrets" / "node.token"),
        }
        # Missing secret files must not prevent teardown of a damaged startup.
        compose.save(state / "compose.env", values)
        return state, values

    def invoke(self, state, *arguments, run):
        with (
            patch.object(sys, "argv", ["compose.py", *arguments, "--state", str(state)]),
            patch.object(compose.os, "umask"),
            patch.object(compose.subprocess, "run", side_effect=run) as docker,
            patch.dict(
                os.environ,
                {"COMPOSE_PROJECT_NAME": "other-project", "LOCALNET_STATE_DIR": "/other"},
            ),
        ):
            compose.main()
        return docker

    def test_reset_requires_confirmation_without_changing_files(self):
        with tempfile.TemporaryDirectory() as directory:
            state, _ = self.create_state(Path(directory))
            before = (state / "compose.env").read_bytes()
            docker = Mock()

            with self.assertRaisesRegex(SystemExit, "reset --yes"):
                self.invoke(state, "reset", run=docker)

            docker.assert_not_called()
            self.assertEqual((state / "compose.env").read_bytes(), before)
            self.assertTrue((state / "chains" / "retained-data").exists())

    def test_reset_removes_volumes_before_generated_state_and_preserves_other_files(self):
        with tempfile.TemporaryDirectory() as directory:
            parent = Path(directory)
            state, _ = self.create_state(parent)
            (state / "operator-notes.txt").write_text("not generated by launcher")
            outside = parent / "outside.txt"
            outside.write_text("unrelated data")
            (state / "media" / "external-link").symlink_to(outside)

            def down(command, **kwargs):
                self.assertEqual(command[-3:], ["down", "--volumes", "--remove-orphans"])
                self.assertEqual(
                    command[command.index("--project-name") + 1], "cleanup-test"
                )
                self.assertEqual(kwargs["env"]["COMPOSE_PROJECT_NAME"], "cleanup-test")
                self.assertEqual(kwargs["env"]["LOCALNET_STATE_DIR"], str(state / "chains"))
                self.assertTrue(kwargs["check"])
                self.assertTrue((state / "chains" / "retained-data").exists())
                self.assertTrue((state / "compose.env").exists())

            docker = self.invoke(state, "reset", "--yes", run=down)

            docker.assert_called_once()
            self.assertEqual([path.name for path in state.iterdir()], ["operator-notes.txt"])
            self.assertEqual(outside.read_text(), "unrelated data")

    def test_failed_docker_teardown_preserves_state_and_manifest(self):
        with tempfile.TemporaryDirectory() as directory:
            state, values = self.create_state(Path(directory))
            docker = Mock(side_effect=subprocess.CalledProcessError(1, ["docker", "compose"]))

            with self.assertRaises(subprocess.CalledProcessError):
                reset_localnet(state, values, docker, confirmed=True, project_root=ROOT)

            self.assertTrue((state / "compose.env").exists())
            self.assertTrue((state / "chains" / "retained-data").exists())
            self.assertTrue((state / "secrets" / "retained-data").exists())

    def test_reset_rejects_external_state_paths_and_linked_directories(self):
        with tempfile.TemporaryDirectory() as directory:
            parent = Path(directory)
            state, values = self.create_state(parent)
            outside = parent / "outside"
            outside.mkdir()
            docker = Mock()

            with self.assertRaisesRegex(SystemExit, "LOCALNET_STATE_DIR"):
                reset_localnet(
                    state,
                    {**values, "LOCALNET_STATE_DIR": str(outside)},
                    docker,
                    confirmed=True,
                    project_root=ROOT,
                )

            (state / "identity-parent" / "retained-data").unlink()
            (state / "identity-parent").rmdir()
            (state / "identity-parent").symlink_to(outside, target_is_directory=True)
            with self.assertRaisesRegex(SystemExit, "linked state path"):
                reset_localnet(state, values, docker, confirmed=True, project_root=ROOT)

            docker.assert_not_called()
            self.assertTrue(outside.exists())

    def test_reset_rejects_repository_and_its_parent(self):
        for state in (ROOT, ROOT.parent):
            with self.subTest(state=state), self.assertRaisesRegex(SystemExit, "dedicated"):
                reset_localnet(state, {}, Mock(), confirmed=True, project_root=ROOT)

    def test_down_removes_containers_but_preserves_volumes_and_state(self):
        with tempfile.TemporaryDirectory() as directory:
            state, _ = self.create_state(Path(directory))
            docker = self.invoke(state, "down", run=lambda *_args, **_kwargs: None)

            command = docker.call_args.args[0]
            self.assertEqual(command[-2:], ["down", "--remove-orphans"])
            self.assertNotIn("--volumes", command)
            self.assertTrue((state / "compose.env").exists())
            self.assertTrue((state / "chains" / "retained-data").exists())

    def test_up_can_initialize_again_after_reset(self):
        with tempfile.TemporaryDirectory() as directory:
            state, values = self.create_state(Path(directory))
            reset_localnet(state, values, Mock(), confirmed=True, project_root=ROOT)
            self.assertFalse(state.exists())

            def run(command, **_kwargs):
                if command[:2] != ["docker", "run"]:
                    return
                identity = state / "identity-parent" / "node"
                identity.mkdir()
                (identity / "node.json").write_text(json.dumps({"node_id": "fresh-node"}))
                (identity / "signing.key").write_bytes(b"fresh test signing key")
                (identity / "service.token").write_text("fresh test service token")

            with patch.object(compose, "Rpc") as rpc:
                rpc.return_value.call.return_value = ["0x0"] * 5
                self.invoke(state, "up", run=run)

            self.assertTrue((state / "compose.env").exists())
            self.assertTrue((state / "secrets" / "custody.key").exists())
            self.assertFalse((state / "chains" / "retained-data").exists())
            retained = dict(
                line.split("=", 1)
                for line in (state / "compose.env").read_text().splitlines()
            )
            self.assertEqual(retained["COMPOSE_PROJECT_NAME"], "other-project")


if __name__ == "__main__":
    unittest.main()
